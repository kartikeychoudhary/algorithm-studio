// Reproduce the small output-head checkpoint; transformer features remain frozen.
import { writeFileSync } from "node:fs";
import {
  corpus,
  tokenize,
  encode,
  vocabulary,
  DIM,
  trainStep,
} from "../lib/learning/llm-model.js";
let head = {
  w: vocabulary.map(() => Array(DIM).fill(0)),
  b: vocabulary.map(() => 0),
};
const examples = corpus.flatMap((text) => {
  const ids = [...tokenize(text).map((t) => t.id), 1];
  return ids
    .slice(1)
    .map((target, i) => ({
      feature: encode(ids.slice(0, i + 1)).features.at(-1),
      target,
    }));
});
for (let epoch = 0; epoch < 400; epoch++)
  for (const example of examples)
    head = trainStep(example.feature, example.target, head, 0.035).head;
const metadata = {
  examples: examples.length,
  epochs: 400,
  rate: 0.035,
  trained: "output projection and bias only; all decoder features frozen",
};
writeFileSync(
  new URL("../lib/data/llm-checkpoint.js", import.meta.url),
  "// Generated by node scripts/train-llm.mjs. Public synthetic corpus; no external weights.\nexport const checkpoint = " +
    JSON.stringify(head) +
    ";\nexport const checkpointInfo = " +
    JSON.stringify(metadata) +
    ";\n",
);
console.log(metadata);
